-- SHOWROOM AR: pelanggan, kendaraan, penjualan, dan pembayaran.
-- Skrip ini aman dijalankan ulang dan tidak menghapus tabel maupun data.

create table if not exists public.pelanggan (
    id_pelanggan bigint generated by default as identity primary key,
    nama_pelanggan varchar(100) not null check (btrim(nama_pelanggan) <> ''),
    no_ktp varchar(30) not null unique check (btrim(no_ktp) <> ''),
    no_telp varchar(20),
    alamat text,
    created_at timestamptz not null default now()
);

create table if not exists public.kendaraan (
    id_kendaraan bigint generated by default as identity primary key,
    merk varchar(60) not null check (btrim(merk) <> ''),
    model varchar(80) not null check (btrim(model) <> ''),
    tahun integer not null check (tahun between 1950 and 2100),
    warna varchar(40),
    harga numeric(15,2) not null check (harga >= 0),
    status varchar(20) not null default 'TERSEDIA'
        check (status in ('TERSEDIA', 'TERJUAL')),
    created_at timestamptz not null default now()
);

create table if not exists public.penjualan (
    id_penjualan bigint generated by default as identity primary key,
    id_pelanggan bigint not null
        references public.pelanggan(id_pelanggan)
        on update cascade on delete restrict,
    id_kendaraan bigint not null unique
        references public.kendaraan(id_kendaraan)
        on update cascade on delete restrict,
    tanggal_penjualan date not null default current_date,
    harga_jual numeric(15,2) not null check (harga_jual >= 0),
    uang_muka numeric(15,2) not null default 0 check (uang_muka >= 0),
    sisa_piutang numeric(15,2) not null default 0 check (sisa_piutang >= 0),
    status varchar(20) not null default 'BELUM LUNAS'
        check (status in ('LUNAS', 'BELUM LUNAS')),
    created_at timestamptz not null default now(),
    check (uang_muka <= harga_jual)
);

create table if not exists public.pembayaran (
    id_pembayaran bigint generated by default as identity primary key,
    id_penjualan bigint not null
        references public.penjualan(id_penjualan)
        on update cascade on delete cascade,
    tanggal_pembayaran date not null default current_date,
    jumlah_bayar numeric(15,2) not null check (jumlah_bayar > 0),
    keterangan varchar(150),
    created_at timestamptz not null default now()
);

create index if not exists idx_penjualan_pelanggan
    on public.penjualan(id_pelanggan);
create index if not exists idx_penjualan_tanggal
    on public.penjualan(tanggal_penjualan);
create index if not exists idx_pembayaran_penjualan
    on public.pembayaran(id_penjualan);
create index if not exists idx_pembayaran_tanggal
    on public.pembayaran(tanggal_pembayaran);

create or replace function public.hitung_piutang_penjualan()
returns trigger
language plpgsql
as $$
declare
    total_bayar numeric(15,2);
begin
    select coalesce(sum(p.jumlah_bayar), 0)
    into total_bayar
    from public.pembayaran p
    where p.id_penjualan = new.id_penjualan;

    if new.uang_muka + total_bayar > new.harga_jual then
        raise exception 'Uang muka dan total pembayaran melebihi harga jual.';
    end if;

    new.sisa_piutang := new.harga_jual - new.uang_muka - total_bayar;
    new.status := case
        when new.sisa_piutang = 0 then 'LUNAS'
        else 'BELUM LUNAS'
    end;
    return new;
end;
$$;

drop trigger if exists trg_hitung_piutang_penjualan on public.penjualan;
create trigger trg_hitung_piutang_penjualan
before insert or update on public.penjualan
for each row
execute function public.hitung_piutang_penjualan();

create or replace function public.hitung_ulang_piutang(p_id_penjualan bigint)
returns void
language plpgsql
as $$
declare
    harga numeric(15,2);
    dp numeric(15,2);
    total_bayar numeric(15,2);
    saldo numeric(15,2);
begin
    select s.harga_jual, s.uang_muka
    into harga, dp
    from public.penjualan s
    where s.id_penjualan = p_id_penjualan
    for update;

    if not found then
        return;
    end if;

    select coalesce(sum(p.jumlah_bayar), 0)
    into total_bayar
    from public.pembayaran p
    where p.id_penjualan = p_id_penjualan;

    if dp + total_bayar > harga then
        raise exception 'Total uang muka dan pembayaran melebihi harga jual.';
    end if;

    saldo := harga - dp - total_bayar;
    update public.penjualan
    set sisa_piutang = saldo,
        status = case when saldo = 0 then 'LUNAS' else 'BELUM LUNAS' end
    where id_penjualan = p_id_penjualan;
end;
$$;

create or replace function public.refresh_piutang_pembayaran()
returns trigger
language plpgsql
as $$
begin
    if tg_op <> 'DELETE' then
        perform public.hitung_ulang_piutang(new.id_penjualan);
    end if;

    if tg_op <> 'INSERT' and
       (tg_op = 'DELETE' or old.id_penjualan is distinct from new.id_penjualan) then
        perform public.hitung_ulang_piutang(old.id_penjualan);
    end if;

    if tg_op = 'DELETE' then
        return old;
    end if;
    return new;
end;
$$;

drop trigger if exists trg_refresh_piutang_insert on public.pembayaran;
drop trigger if exists trg_refresh_piutang_update on public.pembayaran;
drop trigger if exists trg_refresh_piutang_delete on public.pembayaran;
create trigger trg_refresh_piutang_insert
after insert on public.pembayaran
for each row execute function public.refresh_piutang_pembayaran();
create trigger trg_refresh_piutang_update
after update on public.pembayaran
for each row execute function public.refresh_piutang_pembayaran();
create trigger trg_refresh_piutang_delete
after delete on public.pembayaran
for each row execute function public.refresh_piutang_pembayaran();

create or replace function public.sinkron_status_kendaraan()
returns trigger
language plpgsql
as $$
begin
    if tg_op = 'DELETE' then
        update public.kendaraan
        set status = 'TERSEDIA'
        where id_kendaraan = old.id_kendaraan;
        return old;
    end if;

    if tg_op = 'UPDATE' and old.id_kendaraan is distinct from new.id_kendaraan then
        update public.kendaraan
        set status = 'TERSEDIA'
        where id_kendaraan = old.id_kendaraan;
    end if;

    update public.kendaraan
    set status = 'TERJUAL'
    where id_kendaraan = new.id_kendaraan;
    return new;
end;
$$;

drop trigger if exists trg_sinkron_status_kendaraan on public.penjualan;
create trigger trg_sinkron_status_kendaraan
after insert or update of id_kendaraan or delete
on public.penjualan
for each row
execute function public.sinkron_status_kendaraan();
